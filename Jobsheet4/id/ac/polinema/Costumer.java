package Jobsheet4.id.ac.polinema;

public class Costumer {
    private String name;
    private String address;

    public Costumer(String name, String address) {
        this.name = name;
        this.address = address;
    }

    public String getName() {
        return name;
    }

    public String getAddress() {
        return address;
    }
}
